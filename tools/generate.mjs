// The catalog generator of the open renderer: one source for the
// React renderer of the open catalogs. It reads the agentspaces-viz and agentspaces-widgets catalogs, the golden
// surfaces and the look-and-feel schema of agentspaces-a2ui, and writes src/generated/:
//
//   catalogs.ts   the open catalog ids and their component names, in the catalogs' order
//   props.ts      one TypeScript interface per open component from its catalog's property schemas
//   registry.ts   the implementations this package draws, imported from src/components/<viz|widgets>/<Name>.tsx
//   goldens.ts    the golden surfaces the gallery draws and the conformance test checks
//   look.ts       the look-and-feel JSON Schema and its TypeScript type
//   SOURCE.json   the digest of every input and output
//
// Usage: node tools/generate.mjs [--check]
//   --check regenerates in memory and fails when a generated file differs from what the inputs give, when a drawn
//   component has no implementation, or when src/components/viz or src/components/widgets holds a file its catalog
//   does not name.
//
// A host draws the components this package does not yet draw (HOSTED) by registering them (registerComponents).
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const a2ui = resolve(pkg, '..', 'agentspaces-a2ui');
const check = process.argv.includes('--check');

const INPUTS = {
  'agentspaces-viz': join(a2ui, 'src/main/resources/catalogs/agentspaces-viz/catalog.json'),
  'agentspaces-widgets': join(a2ui, 'src/main/resources/catalogs/agentspaces-widgets/catalog.json'),
  goldens: join(a2ui, 'src/test/resources/golden/surfaces.json'),
  look: join(a2ui, 'src/main/resources/catalogs/look-and-feel.schema.json'),
};
/**
 * The open components a host still draws in 0.6.x: the widgets catalog's ApprovalCard and TimelineStrip, which read a
 * platform's own approvals and events. This package draws Chat, FileTree and FilePreview, and
 * their aliases ChatInput, Conversation and FileShare through them.
 */
const HOSTED = { 'agentspaces-viz': [], 'agentspaces-widgets': ['ApprovalCard', 'TimelineStrip'] };
const DRAWN = ['agentspaces-viz', 'agentspaces-widgets'];
/** The folder of each drawn catalog's implementations. */
const FOLDERS = { 'agentspaces-viz': 'viz', 'agentspaces-widgets': 'widgets' };
const OUT = join(pkg, 'src/generated');

const read = p => { if (!existsSync(p)) throw new Error('missing input ' + p); return readFileSync(p, 'utf8'); };
const sha = s => createHash('sha256').update(s).digest('hex');
const inputs = Object.fromEntries(Object.entries(INPUTS).map(([k, p]) => [k, read(p)]));
const catalogs = Object.fromEntries(['agentspaces-viz', 'agentspaces-widgets'].map(k => [k, JSON.parse(inputs[k])]));
const goldens = JSON.parse(inputs.goldens);
const look = JSON.parse(inputs.look);
const header = '// GENERATED by tools/generate.mjs from the agentspaces-a2ui catalogs; do not edit (the build checks this file against its inputs).\n';
const names = id => Object.keys(catalogs[id].components);
const drawn = id => names(id).filter(n => !(HOSTED[id] ?? []).includes(n));

const catalogsTs = header + `/** The open catalogs: the id a surface names and the components each declares, in the catalogs' order. */
export const OPEN_CATALOGS = {
${Object.keys(catalogs).map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(names(k))},`).join('\n')}
} as const;
export type OpenCatalogId = keyof typeof OPEN_CATALOGS;
/** The open components a host draws until this package does (registerComponents). */
export const HOSTED: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(HOSTED)};
`;

function tsType(schema) {
  if (!schema || typeof schema !== 'object') return 'unknown';
  if (schema.enum) return schema.enum.map(v => JSON.stringify(v)).join(' | ');
  if (schema.oneOf) return schema.oneOf.map(tsType).join(' | ');
  switch (schema.type) {
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return `Array<${tsType(schema.items)}>`;
    case 'object': {
      if (!schema.properties) return 'Record<string, unknown>';
      const req = new Set(schema.required || []);
      return `{ ${Object.entries(schema.properties).map(([k, v]) => `${k}${req.has(k) ? '' : '?'}: ${tsType(v)}`).join('; ')} }`;
    }
    default: return 'unknown';
  }
}
let propsTs = header + `/** The properties of each open component as its catalog declares them; a component's id and name come with every A2UI component. */\n`;
for (const id of Object.keys(catalogs)) {
  for (const [name, spec] of Object.entries(catalogs[id].components)) {
    const req = new Set(spec.required || []);
    propsTs += `\n/** ${id}: ${(spec.description || '').replace(/\*\//g, '* /')} */\nexport interface ${name}Props {\n  id: string;\n  component: ${JSON.stringify(name)};\n`;
    for (const [k, v] of Object.entries(spec.properties || {})) propsTs += `  ${k}${req.has(k) ? '' : '?'}: ${tsType(v)};${v.description ? '   // ' + v.description : ''}\n`;
    propsTs += `  [extra: string]: unknown;\n}\n`;
  }
}
propsTs += `\n/** What each open catalog requires of each component, by catalog id then name. */\nexport const OPEN_REQUIRED: Record<string, Record<string, readonly string[]>> = {\n${Object.keys(catalogs).map(id => `  ${JSON.stringify(id)}: { ${Object.entries(catalogs[id].components).map(([n, s]) => `${n}: ${JSON.stringify(s.required || [])}`).join(', ')} },`).join('\n')}\n};\n`;

let registryTs = header + `import type { Implementation } from '../renderer/implementation';\n`;
for (const id of DRAWN) for (const name of drawn(id)) registryTs += `import { ${name} as ${FOLDERS[id]}_${name} } from '../components/${FOLDERS[id]}/${name}';\n`;
registryTs += `\n/** The implementations this package draws, by catalog id then name; the basic catalog is web_core's. */\nexport const OPEN_IMPLEMENTATIONS: Record<string, Record<string, Implementation>> = {\n`;
for (const id of DRAWN) registryTs += `  ${JSON.stringify(id)}: { ${drawn(id).map(n => `${n}: ${FOLDERS[id]}_${n}`).join(', ')} },\n`;
registryTs += `};\n`;

const goldensTs = header + `/** The golden surfaces of agentspaces-a2ui (src/test/resources/golden/surfaces.json): the envelopes and the text a person must find; a frame component has four (full, empty, loading, error). */\nexport interface GoldenSurface { name: string; state?: string; surfaceId: string; catalogId: string; envelopes: Array<Record<string, unknown>>; expectText: string[] }\nexport const GOLDENS: GoldenSurface[] = ${JSON.stringify(goldens.surfaces, null, 2)};\n`;
const lookTs = header + `/** The look-and-feel JSON Schema of the open library, and the shape a renderer takes. */\nexport const LOOK_SCHEMA = ${JSON.stringify(look, null, 2)} as const;
export interface ModeTokens {
  color: { surface: string; ink: string; inkMuted?: string; accent: string; categorical: string[]; sequential?: string; diverging?: { warm?: string; neutral?: string; cool?: string }; status: Record<string, string> & { good: string; warning: string; serious: string; critical: string } };
  type?: { family?: string; scale?: number[] };
  space?: { unit?: number; density?: 'comfortable' | 'compact' };
  radius?: number;
  shadow?: 'none' | 'soft' | 'strong';
}
export interface LookAndFeel { schemaVersion: 1; id: string; name?: string; tokens: ModeTokens; dark?: ModeTokens; texture?: { fill?: 'diagonal' | 'dots' | 'none' }; validated?: { at?: string; by?: string; ok?: boolean }; version?: number; state?: string }
`;

const outputs = { 'catalogs.ts': catalogsTs, 'props.ts': propsTs, 'registry.ts': registryTs, 'goldens.ts': goldensTs, 'look.ts': lookTs };
const source = { inputs: Object.fromEntries(Object.entries(INPUTS).map(([k, p]) => [k, { path: p.replace(resolve(pkg, '..') + '/', ''), sha256: sha(inputs[k]) }])), outputs: Object.fromEntries(Object.entries(outputs).map(([k, v]) => [k, sha(v)])) };
outputs['SOURCE.json'] = JSON.stringify(source, null, 2) + '\n';

const problems = [];
for (const id of DRAWN) {
  const dir = join(pkg, 'src/components', FOLDERS[id]);
  for (const name of drawn(id)) if (!existsSync(join(dir, name + '.tsx'))) problems.push(`${id}/${name}: write src/components/${FOLDERS[id]}/${name}.tsx`);
  for (const f of readdirSync(dir)) if (f.endsWith('.tsx') && !drawn(id).includes(f.slice(0, -4))) problems.push(`src/components/${FOLDERS[id]}/${f} is not a component this package draws: add it to the catalog or remove it`);
}
if (check) {
  for (const [f, text] of Object.entries(outputs)) {
    const p = join(OUT, f);
    if (!existsSync(p)) problems.push(`${f} is not generated: run npm run generate`);
    else if (readFileSync(p, 'utf8') !== text) problems.push(`${f} differs from its inputs: run npm run generate (a hand edit is lost there)`);
  }
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [f, text] of Object.entries(outputs)) writeFileSync(join(OUT, f), text);
  console.log(`generated ${Object.keys(outputs).length} files in src/generated from ${Object.keys(catalogs).length} catalogs (${Object.values(catalogs).map(c => Object.keys(c.components).length).reduce((a, b) => a + b)} components)`);
}
if (problems.length) { console.error(problems.map(p => '  ' + p).join('\n')); process.exit(1); }
if (check) console.log('generate: the generated files match their inputs; every drawn component has its implementation');
